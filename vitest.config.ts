// Единственная задача этой конфигурации — не пускать швы на живом tmux в параллель с
// остальными тестами. Они держат настоящие tmux-сессии с настоящими процессами (у шва
// Gradle — около полуминуты), и от такой нагрузки на машине рвался соседний relay-тест
// на 16-мегабайтный фрейм (примерно раз из трёх). Группы проектов запускаются по
// возрастанию groupOrder: сначала вся сюита, потом — отдельно от неё — группа живых
// tmux-швов. Отдельно значит «без чужих тестов рядом», а не «по одному файлу»: внутри
// группы файлы идут параллельно друг другу, каждый на своём сокете `-L`. Порогов чужих
// тестов это не трогает.
//
// Если краснота вернётся уже внутри группы, первый рычаг — `fileParallelism: false` для
// неё: швы выстроятся в очередь. Сейчас он не поставлен намеренно — доказательств, что
// живые швы мешают друг другу, нет.
//
// Отбор по имени файла, а не по списку: живой шов называется `*.tmux.test.ts` и попадает
// в свою группу сам. Список конкретных файлов пополнялся бы по памяти автора, и первый же
// забытый шов вернул бы настоящий tmux в общий прогон — ровно так сюда и попал
// session-feed.tmux.test.ts.
import { configDefaults, defineConfig } from 'vitest/config';

const TMUX_SEAM = '**/*.tmux.test.ts';
// Внутри репозитория живёт git-worktree владельца: его копия сюиты иначе
// попадает в прогон и удваивает число тестов. Проекты vitest общий exclude не
// наследуют, поэтому список раздаётся в обе группы.
const BASE_EXCLUDE = [...configDefaults.exclude, '**/.worktrees/**'];

export default defineConfig({
  test: {
    projects: [
      {
        test: {
          name: 'suite',
          exclude: [...BASE_EXCLUDE, TMUX_SEAM],
          sequence: { groupOrder: 0 },
        },
      },
      {
        test: {
          name: 'tmux',
          exclude: BASE_EXCLUDE,
          include: [TMUX_SEAM],
          sequence: { groupOrder: 1 },
        },
      },
    ],
  },
});
