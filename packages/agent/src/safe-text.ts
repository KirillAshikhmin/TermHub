// Обеззараживание строк, которые приходят от недоверенной стороны (пир пейринга,
// relay) и в итоге печатаются в терминал оператора.
//
// Зачем: терминал исполняет то, что в него пишут. Escape-последовательности в имени
// устройства или в коде ошибки relay позволяли стереть/подделать строку в выводе
// `termhub devices` — а это ровно тот список, по которому принимается решение об
// отзыве доступа, — и записать в буфер обмена оператора через OSC 52 (termhub setup
// включает в tmux `set -g set-clipboard on`). Bidi-override дополнительно
// переставляет символы при отрисовке, подделывая колонку fingerprint.

/** Потолок длины имени устройства: список устройств должен оставаться читаемым. */
export const MAX_DEVICE_NAME = 64;

/** Управляющие символы C0/C1 (включая ESC, CR, LF, TAB) и bidi-переключатели.
 *  Собрано через new RegExp из ASCII-строки, чтобы в исходнике не было сырых
 *  управляющих байтов. */
const UNSAFE_TEXT = new RegExp('[\\u0000-\\u001f\\u007f-\\u009f\\u200e\\u200f\\u202a-\\u202e\\u2066-\\u2069]', 'g');

/** Убирает всё, что может переписать уже отрисованное или переставить символы. */
export function stripUnsafe(value: string): string {
  return value.replace(UNSAFE_TEXT, '');
}

/** Приводит имя устройства к безопасному виду в момент СОХРАНЕНИЯ (граница доверия).
 *  Санитизация на месте печати — вторая линия: в authorized.json могли остаться
 *  имена, записанные до этой проверки. */
export function sanitizeDeviceName(raw: string): string {
  const clean = stripUnsafe(raw).trim().slice(0, MAX_DEVICE_NAME);
  return clean || 'device';
}
